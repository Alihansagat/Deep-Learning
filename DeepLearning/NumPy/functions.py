import numpy as np
# Numpy Universal Functions

np1 = np.array([4, -2, 3, 0, 5, 6, 7, 8, 9])

#! Square of each element
# print(np.sqrt(np1))

#! Absolute value
print(np.absolute(np1))

#! Exponentials
print(np.exp(np1))

#! Sign negative and positive
print(np1)
print(np.sign(np1))

# Trig(Trigonometric) sin cos tag
print(np.sin(np1))
print(np.cos(np1))
print(np.log(np1))

